// node tools/toolkit-check/test-cadence.mjs — bin/closing's cadence items (toolkit-standard §D 11).
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { execFileSync } from "node:child_process";
import { alerts, cadence, queue, reviewBranches } from "./closing.mjs";
import { writeFileSync, mkdirSync } from "node:fs";
let pass = 0, fail = 0;
const ok = (name, c) => { if (c) pass++; else { fail++; console.log("FAIL " + name); } };
const repo = mkdtempSync(join(tmpdir(), "cadence-"));
const git = (...a) => execFileSync("git", ["-C", repo, ...a], { encoding: "utf8" });
git("init", "-q"); git("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "--allow-empty", "-m", "work");
const now = Date.now();
let r = cadence(repo, now);
ok("no Review: commit means a review is owed", r.some((l) => /review is owed \(last never/.test(l)));
git("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "--allow-empty", "-m", "a change\n\nReview: two Explore reviewers on this diff");
r = cadence(repo, now);
ok("a change's own Review: trailer is not the independent review", r.some((l) => /review is owed \(last never/.test(l)));
git("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "--allow-empty", "-m", "a merge\n\nReview: independent — an Explore agent on this merge");
r = cadence(repo, now);
ok("a change's trailer calling its own review independent does not close the periodic one", r.some((l) => /review is owed \(last never/.test(l)));
git("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "--allow-empty", "-m", "a review\n\nReview: independent — four fresh agents on tools/toolkit-check/review.md");
r = cadence(repo, now);
ok("a recent Review: commit leaves nothing open", r.length === 0);
r = cadence(repo, now + 15 * 864e5);
ok("fifteen days after the last review, one is owed again", r.length === 1 && /review is owed/.test(r[0]));
// the security alerts: counted by severity, and a gh that cannot answer is "not read", never none
let asked = [];
let a = alerts(repo, (args) => { asked = args; return "high\nmedium\nhigh\n"; });
ok("every page of alerts is read", asked.includes("--paginate"));
ok("open alerts are counted by severity", a.open === 3 && a.by.high === 2 && a.by.medium === 1);
a = alerts(repo, () => "");
ok("no open alert is zero, not unread", a.open === 0 && !a.unread);
a = alerts(repo, () => { const e = new Error("gh failed"); e.stderr = "To get started with GitHub CLI, please run:  gh auth login\n"; throw e; });
ok("a gh signed out is unread, with what it said", a.open === undefined && /gh auth login/.test(a.unread));
// the queue: computed from git, never stored — what was left for later since the last periodic review
const c = (...a) => git("-c", "user.name=t", "-c", "user.email=t@t", ...a);
const proj = mkdtempSync(join(tmpdir(), "cadence-proj-"));
const pg = (...a) => execFileSync("git", ["-C", proj, "-c", "user.name=t", "-c", "user.email=t@t", ...a], { encoding: "utf8" });
pg("init", "-q");
// before the last periodic review: already read by it, so not queued again
execFileSync("git", ["-C", proj, "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "--allow-empty", "-m", "old\n\nToolkit: none — read by the last review"], { env: { ...process.env, GIT_COMMITTER_DATE: "2020-01-01T00:00:00Z", GIT_AUTHOR_DATE: "2020-01-01T00:00:00Z" } });
pg("commit", "-q", "--allow-empty", "-m", "a\n\nToolkit: none — this board's own rule");
pg("commit", "-q", "--allow-empty", "-m", "b\n\nToolkit: none — this board's own rule");
pg("commit", "-q", "--allow-empty", "-m", "c\n\nToolkit: skills/x/SKILL.md");
mkdirSync(join(repo, "tools"), { recursive: true });
writeFileSync(join(repo, "tools/README.md"), "# T\n\n## Known limits\n\nOne.\n\n*Open:* a real one.\n\nProse that names an\n*Open:* line, wrapped, and mid-line *Open:* too.\n\n- *Open:* in a list.\n> *Open:* in a quote.\n### After a heading\n*Open:* under it.\n\n\t*Open:* tab-indented.\n");
c("add", "tools/README.md"); c("commit", "-q", "-m", "docs");
let q = queue([["toolkit", repo], ["board", proj]], repo);
ok("the queue reads from the last periodic review", /^\d{4}-\d\d-\d\d$/.test(q.since));
ok("a project's Toolkit: none reasons are queued once each, counted", q.items.filter((i) => i.kind === "toolkit-none" && i.source === "board").length === 1 && q.items.find((i) => i.source === "board").count === 2);
ok("a Toolkit: none line from before the last review is not queued again", !q.items.some((i) => /read by the last review/.test(i.text)));
ok("a Toolkit: line naming a file is not queued", !q.items.some((i) => /skills\/x/.test(i.text)));
ok("a Known limits section is queued by its place", q.items.some((i) => i.kind === "open-edge" && i.text === "tools/README.md:3"));
ok("an *Open:* paragraph, list item, quote or line under a heading is queued; prose naming the marker is not", JSON.stringify(q.items.filter((i) => i.kind === "open-edge").map((i) => i.text)) === JSON.stringify(["tools/README.md:3", "tools/README.md:7", "tools/README.md:12", "tools/README.md:13", "tools/README.md:15", "tools/README.md:17"]));
// review branches: one bin/review left is named until it is merged
c("branch", "-M", "main");
ok("no review branch, nothing named", reviewBranches(repo).length === 0);
c("checkout", "-q", "-b", "review/2026-11-12"); c("commit", "-q", "--allow-empty", "-m", "review: a fix"); c("checkout", "-q", "main");
let rb = reviewBranches(repo);
ok("an unmerged review branch is named with its commits", rb.length === 1 && rb[0].branch === "review/2026-11-12" && rb[0].commits === 1);
c("merge", "-q", "--no-ff", "review/2026-11-12", "-m", "merge review");
ok("a merged review branch is not named again", reviewBranches(repo).length === 0);
console.log(pass + " passed, " + fail + " failed");
process.exit(fail ? 1 : 0);
