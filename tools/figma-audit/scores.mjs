#!/usr/bin/env node
// The score report as markdown, from the audit record: figma-components-audit's
// on-request 0–100 component scores (SKILL.md "Scoring — on request only"),
// computed by the model the dashboard applies (score-model.mjs) over the
// skill's scanner/scoring.json and checks.json, never by hand (toolkit-standard
// §D 23). The same record always gives the same table.
//
//   node tools/figma-audit/scores.mjs --data <project>/audit/<fileKey>.json
//        [--file-key <key>] [--sets <scan.json>] [--scanner <dir>] [--json]
//
//   --sets     the components scored: a JSON array of names or of the scan's
//              audited entries ({ set, id }); an id deep-links the row. By
//              default, the sets the record's last sweep fingerprinted.
//   --scanner  the skill's scanner/ (default: this repo's)
//   --json     the scores document instead, as the record keeps it
//              (scores/<fileKey>), to write in the same pass as the rows
//
// Markdown on stdout: one row per component, worst first, a column per
// dimension, the delta against the record's last scores where it has them,
// then the median. On stderr, one line per gap the run fills by hand.
import { readFileSync, realpathSync, existsSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { computeScores } from "./score-model.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
export const GENERATED = "<!-- Generated by tools/figma-audit/scores.mjs from the audit record. Regenerate it; never edit it. -->";

// A column's heading from its dimension's name: the first letter, or the first
// two where a dimension before it took that letter (Tokens T, States S,
// Structure St). Names stay scoring.json's; this holds none.
export function abbreviations(names) {
  const taken = new Set(), out = {};
  for (const n of names) {
    let a = n[0].toUpperCase();
    for (let i = 2; taken.has(a) && i <= n.length; i++) a = n[0].toUpperCase() + n.slice(1, i);
    taken.add(a); out[n] = a;
  }
  return out;
}

const signed = (d) => (d > 0 ? "+" : "−") + Math.abs(d);
const PIPE = /\s*\|\s*/g;

export function renderScores(record, scoring, catalogue, opts = {}) {
  const libs = Object.keys(record.libraries || {});
  const fileKey = opts.fileKey || (libs.length === 1 ? libs[0] : null);
  if (!fileKey) throw new Error("name the library with --file-key: " + (libs.join(", ") || "the record has none"));
  const lib = (record.libraries || {})[fileKey] || {};
  const base = String(lib.figmaUrl || "").split(/[?#]/)[0];
  const gaps = [];

  let sets = opts.sets ? opts.sets.map((s) => (typeof s === "string" ? { set: s } : s)).filter((s) => s && s.set) : null;
  if (!sets) {
    const fp = ((record.fingerprints || {})[fileKey] || {}).sets;
    if (fp && Object.keys(fp).length) sets = Object.keys(fp).sort((a, b) => a.localeCompare(b, "en")).map((set) => ({ set }));
  }
  if (!sets) throw new Error("the record has no fingerprints for " + fileKey + ": pass --sets with the components scanned");

  const doc = computeScores(sets, record.rows, scoring, catalogue, opts.at);
  if (!doc) throw new Error("the scoring model has no dimensions");
  const names = Object.keys(scoring.dimensions);
  const ab = abbreviations(names);
  const prev = (record.scores || {})[fileKey];
  const before = prev && Array.isArray(prev.rows) ? Object.fromEntries(prev.rows.map((r) => [r.name, r])) : null;
  const id = Object.fromEntries(sets.filter((s) => s.id).map((s) => [s.set, s.id]));

  const cell = (now, was) => (now == null ? "—" : was == null || was === now ? String(now) : now + " (" + signed(now - was) + ")");
  const where = (name) => {
    const code = "`" + String(name).replace(/`/g, "'").replace(PIPE, " · ") + "`";
    return base && id[name] ? "[" + code + "](" + base + "?node-id=" + String(id[name]).replace(/:/g, "-") + ")" : code;
  };
  const rows = doc.rows.slice().sort((a, b) => a.score - b.score || a.name.localeCompare(b.name, "en"));
  const out = [GENERATED, ""];
  const cols = ["Score", ...names.map((n) => ab[n]), "Component", "Flags"];
  out.push("| " + cols.join(" | ") + " |", "|" + cols.map(() => "---").join("|") + "|");
  for (const r of rows) {
    const was = before && before[r.name];
    out.push("| " + [
      cell(r.score, was ? was.score : null),
      ...names.map((n) => cell(r.d[n], was && was.d ? was.d[n] : null)),
      where(r.name),
      r.notes.join("; ").replace(PIPE, " · ")
    ].join(" | ") + " |");
  }
  out.push("");
  out.push("**Key:** " + names.map((n) => ab[n] + " " + n).join(" · ") + (before ? " · (±n) against the scores of " + String(prev.at || "the last run").slice(0, 10) : ""));
  out.push("", "**Median:** " + (doc.median == null ? "no components scored" : doc.median) + (before && prev.median != null && doc.median != null && prev.median !== doc.median ? " (" + signed(doc.median - prev.median) + ")" : ""));

  if (!base) gaps.push("the record's library has no figmaUrl, so no row carries a deep link");
  else if (rows.some((r) => !id[r.name])) gaps.push("no node id for " + rows.filter((r) => !id[r.name]).length + " components (pass --sets with the scan's audited entries), so their rows carry no deep link");
  if (!before) gaps.push("no earlier scores for " + fileKey + " in the record: a first report states no delta");
  gaps.push("the metrics block (Coverage · Scope · Date) closes the report, as the fix queue's does");
  return { markdown: out.join("\n") + "\n", doc, gaps };
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const arg = (n) => { const i = args.indexOf(n); return i > -1 ? args[i + 1] : null; };
  if (!arg("--data")) { console.error("usage: node tools/figma-audit/scores.mjs --data <record> [--file-key <key>] [--sets <scan.json>] [--scanner <dir>] [--json]"); process.exit(2); }
  let res;
  try {
    const scanner = arg("--scanner") || join(HERE, "..", "..", "skills", "figma-components-audit", "scanner");
    if (!existsSync(join(scanner, "scoring.json"))) throw new Error("no scoring.json in " + scanner + " — pass --scanner <dir> pointing at the skill's scanner/");
    const scoring = JSON.parse(readFileSync(join(scanner, "scoring.json"), "utf8"));
    const catalogue = existsSync(join(scanner, "checks.json")) ? JSON.parse(readFileSync(join(scanner, "checks.json"), "utf8")) : null;
    const record = JSON.parse(readFileSync(arg("--data"), "utf8"));
    const named = basename(arg("--data"), ".json");
    const libs = Object.keys(record.libraries || {});
    let sets = null;
    if (arg("--sets")) {
      const s = JSON.parse(readFileSync(arg("--sets"), "utf8"));
      sets = Array.isArray(s) ? s : s && Array.isArray(s.audited) ? s.audited : null;
      if (!sets) throw new Error("--sets: a JSON array of names or of { set, id }, or a scan with `audited`");
    }
    res = renderScores(record, scoring, catalogue, {
      fileKey: arg("--file-key") || (!libs.length && /^[0-9A-Za-z]{22,128}$/.test(named) ? named : undefined), sets
    });
    if (!catalogue) res.gaps.unshift("no checks.json beside scoring.json: no dimension could be marked unscanned");
  } catch (e) { console.error(e.message); process.exit(1); }
  process.stdout.write(args.includes("--json") ? JSON.stringify(res.doc, null, 2) + "\n" : res.markdown);
  for (const g of res.gaps) console.error("written by the run: " + g);
}
