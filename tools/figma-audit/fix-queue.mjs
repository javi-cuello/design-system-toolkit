#!/usr/bin/env node
// The fix queue as markdown, from the audit record: figma-components-audit's
// chat report and its .md mirror (SKILL.md, "Chat report template"), generated
// rather than assembled per run (toolkit-standard §D 23). The record is the
// source; the same record always gives the same text.
//
//   node tools/figma-audit/fix-queue.mjs --data <project>/audit/<fileKey>.json
//        [--file-key <key>] [--owner <skill>] [--chat] [--links]
//        [--held-back <text>] [--not-scanned <text>]
//
//   (default)  the .md mirror: a Done column, what is wrong beside the fix,
//              and every Where cell a deep link into the file
//   --chat     the chat report: no Done column, one Fix cell, and no URLs
//              (a terminal prints a link as its whole raw URL)
//   --links    with --chat, for a surface that renders links (claude.ai)
//   --owner    one skill's rows; every owner's open rows otherwise
//   --held-back, --not-scanned  the run's own words for the closing line,
//              which no record holds
//
// Markdown on stdout. On stderr, one line per gap the run fills by hand: the
// held-back / not-scanned line when not given, a cell past the ~120-character
// budget, a record with no run to state the delta and the metrics from.
//
// Open means what the page means (audit-row.mjs `isOpen`). Buckets are the
// record's three; rows.mjs clamps every filing into b1–b3, so a breaking
// change is a b3 question here as it is on the page.
import { readFileSync, realpathSync } from "node:fs";
import { basename } from "node:path";
import { fileURLToPath } from "node:url";
import { isOpen } from "./audit-row.mjs";
import { LEGACY_OWNER } from "./rows.mjs";
export const GENERATED = "<!-- Generated by tools/figma-audit/fix-queue.mjs from the audit record. Regenerate it; never edit it. -->";
const BUDGET = 120;

const HEAD = {
  b1: "### 1 · Approve & I fix (one approval applies all)",
  b2: "### 2 · Quick manual fixes",
  b3: "### 3 · Decide"
};
const KEY = "**Key:** 🔴 error · 🟡 warning · 🔵 needs ruling · ◽ preference · ⚠️ = user-visible impact, leads the queue";
const PROMPT = 'Answer any row by its number or name + choice (e.g. "3.2: accept" or "tooltip: accept") and I\'ll action it.';
const RANK = { error: 0, warn: 1, pref: 2 };

// Stored claims are markup (rows.mjs escapes what a scanner or model wrote;
// authored rows carry <code> and <b>). A cell holds no pipe: an escaped one
// still splits the row in a terminal, so it becomes the · the template uses.
// Entities are unescaped inside code only: outside it an unescaped tag would
// render as HTML, so an escaped one becomes a code span, and a lone < stays.
const PIPE = /\s*\|\s*/g;
const unescape = (s) => s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, "&");
const prose = (s) => s
  .replace(/<\/?(b|strong)>/g, "**")
  .replace(/<[^>]+>/g, "")
  .replace(/&lt;([A-Za-z/!?][^<>&]*)&gt;/g, (m, tag) => "`<" + unescape(tag) + ">`")
  .replace(/&lt;(?![A-Za-z/!?])/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'")
  .replace(/&amp;(?!(lt|gt|amp|quot|#\d+);)/g, "&");
export const text = (t) => String(t == null ? "" : t)
  .split(/<code>([\s\S]*?)<\/code>/)
  .map((seg, i) => (i % 2 ? "`" + unescape(seg) + "`" : prose(seg)))
  .join("")
  .replace(PIPE, " · ")
  .replace(/\s+/g, " ").trim();
const claims = (v) => (Array.isArray(v) ? v : v ? [v] : []).map(text).filter(Boolean);

const marker = (r) => (r.sev === "error" ? "🔴" : r.sev === "pref" ? "◽" : r.bucket === "b3" ? "🔵" : "🟡") + (r.visible ? "⚠️" : "");
const order = (a, b) => (b[1].visible ? 1 : 0) - (a[1].visible ? 1 : 0)
  || (RANK[a[1].sev] ?? 1) - (RANK[b[1].sev] ?? 1)
  || String(a[1].where).localeCompare(String(b[1].where), "en")
  || (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0);

export function renderQueue(record, opts = {}) {
  const libs = Object.keys(record.libraries || {});
  const fileKey = opts.fileKey || (libs.length === 1 ? libs[0] : null);
  if (!fileKey) throw new Error("name the library with --file-key: " + (libs.join(", ") || "the record has none"));
  const lib = (record.libraries || {})[fileKey] || {};
  const mirror = !opts.chat, linked = mirror || !!opts.links;
  const base = String(lib.figmaUrl || "").split(/[?#]/)[0];
  const gaps = [];
  if (linked && !base) gaps.push("the record's library has no figmaUrl, so no Where cell carries a deep link");

  const where = (r) => {
    const code = "`" + String(r.where || "").replace(/`/g, "'").replace(PIPE, " · ") + "`";   // a code span does not protect a pipe in a table
    return linked && base && r.node ? "[" + code + "](" + base + "?node-id=" + String(r.node).replace(/:/g, "-") + ")" : code;
  };
  const cell = (xs, at) => {
    for (const x of xs) if (x.length > BUDGET) gaps.push(at + ": a claim of " + x.length + " characters, over the ~" + BUDGET + " budget; shorten it in the record or move it below the table");
    return xs.join(mirror ? "<br>" : " · ");
  };

  const rows = Object.entries(record.rows || {})
    .filter(([, r]) => r && isOpen(r) && (!opts.owner || (r.owner || LEGACY_OWNER) === opts.owner));

  // The delta, and the closing metrics, come from the library's latest audit run.
  const runs = Object.values(record.runs || {}).filter((r) => r && r.fileKey === fileKey && (r.kind || "audit") === "audit")
    .sort((a, b) => String(a.at).localeCompare(String(b.at)));
  const run = runs[runs.length - 1];
  const out = mirror ? [GENERATED, ""] : [];
  if (!run) gaps.push("the record has no audit run for " + fileKey + ": the delta line and the metrics block are the run's to write");
  else if (runs.length > 1) out.push("**Re-run:** " + run.sets + " sets scanned · **" + (run.found || 0) + " new** · **" + (run.cleared || 0) + " fixed** · everything below is still open.", "");
  else out.push("Audited " + run.sets + " sets, " + run.variants + " variants.", "");
  out.push(KEY, "");

  if (!rows.length) out.push("Nothing open.", "");
  for (const b of ["b1", "b2", "b3"]) {
    const mine = rows.filter(([, r]) => (r.bucket || "b3") === b).sort(order);
    if (!mine.length) continue;
    const N = b.slice(1);
    const cols = b === "b3"
      ? ["#", "Sev", "Where", "Question", "Rec"]
      : mirror ? ["#", "Sev", "Where", "What's wrong", "Fix"] : ["#", "Sev", "Where", "Fix"];
    if (mirror) cols.unshift("Done");
    out.push(HEAD[b], "| " + cols.join(" | ") + " |", "|" + cols.map(() => "---").join("|") + "|");
    mine.forEach(([, r], i) => {
      const n = N + "." + (i + 1);
      const wrong = claims(r.fix).length ? claims(r.fix) : claims(r.check);
      const fix = claims(r.rec);
      const cells = b === "b3"
        ? [cell(wrong, n), cell(fix, n)]
        : mirror ? [cell(wrong, n), cell(fix, n)] : [cell(fix.length ? fix : wrong, n)];
      const line = [n, marker(r), where(r), ...cells];
      if (mirror) line.unshift(r.done ? "[x]" : "[ ]");
      out.push("| " + line.join(" | ") + " |");
    });
    out.push("");
  }

  const close = [opts.heldBack && "Held back: " + text(opts.heldBack).replace(/\.$/, "") + ".", opts.notScanned && "Not scanned: " + text(opts.notScanned).replace(/\.$/, "") + "."].filter(Boolean);
  if (close.length) out.push("*" + close.join(" ") + "*", "");
  if (!opts.heldBack) gaps.push("the Held back part of the closing line: pass --held-back, or say none is held back");
  if (!opts.notScanned) gaps.push("the Not scanned part of the closing line: pass --not-scanned with the checks this run did not exercise");
  if (!mirror) out.push(PROMPT, "");

  if (run) {
    const m = lib.metrics || {};
    const n = typeof m.bound === "number" ? m.bound + (m.unbound || 0) : null;
    out.push("Coverage: " + (run.coverage == null ? "not measured" : run.coverage + "%") + " (" + (run.trigger === "changes" ? "changed sets" : "full") + (n == null ? "" : ", " + n + " bindings") + ")",
             "Scope: " + text(run.scope || run.sets + " sets"),
             "Date: " + String(run.at).slice(0, 10));
  }
  return { markdown: out.join("\n").replace(/\n+$/, "") + "\n", gaps };
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const arg = (n) => { const i = args.indexOf(n); return i > -1 ? args[i + 1] : null; };
  if (!arg("--data")) { console.error("usage: node tools/figma-audit/fix-queue.mjs --data <record> [--file-key <key>] [--owner <skill>] [--chat] [--links] [--held-back <text>] [--not-scanned <text>]"); process.exit(2); }
  let res;
  try {
    const record = JSON.parse(readFileSync(arg("--data"), "utf8"));
    // a record is named for its library (audit/<fileKey>.json); an older record holds it nowhere else, so
    // the name is read only where the record names no library, never over the ones it does
    const named = basename(arg("--data"), ".json");
    const libs = Object.keys(record.libraries || {});
    res = renderQueue(record, {
      fileKey: arg("--file-key") || (!libs.length && /^[0-9A-Za-z]{22,128}$/.test(named) ? named : undefined), owner: arg("--owner"), chat: args.includes("--chat"), links: args.includes("--links"),
      heldBack: arg("--held-back"), notScanned: arg("--not-scanned")
    });
  } catch (e) { console.error(e.message); process.exit(1); }
  process.stdout.write(res.markdown);
  for (const g of res.gaps) console.error("written by the run: " + g);
}
