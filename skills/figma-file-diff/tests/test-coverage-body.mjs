// The coverage test as it runs: scripts/coverage-body.mjs joins serialise.js's
// serialiser to scripts/coverage-test.js, and the body is run here against a
// stand-in `figma` whose nodes hold their properties as plain fields. Every
// mutation must move the hash with today's serialiser, and a serialiser that
// stops reading a property must show it as a blind spot.
// Run: node tests/test-coverage-body.mjs   (exits non-zero on failure)
import fs from "node:fs";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
import { coverageBody } from "../scripts/coverage-body.mjs";

const read = (f) => fs.readFileSync(fileURLToPath(new URL(f, import.meta.url)), "utf8");
const SERIALISE = read("../scripts/serialise.js"), TEST = read("../scripts/coverage-test.js");
const Async = Object.getPrototypeOf(async function () {}).constructor;

// A new node with the defaults Figma gives one: what a mutation moves away from.
function standIn() {
  const node = (type, own) => {
    const n = { type, name: type === "TEXT" ? "Text" : "Frame", visible: true, opacity: 1, blendMode: "PASS_THROUGH", rotation: 0, width: 100, height: 100,
      fills: [], strokes: [], strokeTopWeight: 1, strokeRightWeight: 1, strokeBottomWeight: 1, strokeLeftWeight: 1, strokeAlign: "INSIDE", dashPattern: [], effects: [],
      maxWidth: null, minWidth: null, maxHeight: null, minHeight: null, cornerRadius: 0, children: [], removed: false,
      // as Figma does: a resize fixes both axes (seen live)
      resize(w, h) { n.width = w; n.height = h; if ("layoutSizingHorizontal" in n) n.layoutSizingHorizontal = n.layoutSizingVertical = "FIXED"; },
      appendChild(c) { n.children.push(c); c.parent = n; },
      insertChild(i, c) { n.children = n.children.filter((x) => x !== c); n.children.splice(i, 0, c); c.parent = n; },
      remove() { n.removed = true; }, ...own };
    made.push(n);
    return n;
  };
  const made = [];
  const figma = {
    mixed: Symbol("mixed"), root: { name: "Scratch" }, made,
    loadFontAsync: async () => {}, loadAllPagesAsync: async () => {},
    variables: { getLocalVariablesAsync: async () => [] },
    getLocalPaintStylesAsync: async () => [], getLocalTextStylesAsync: async () => [], getLocalEffectStylesAsync: async () => [],
    createFrame: () => node("FRAME", { clipsContent: true, layoutMode: "NONE", paddingTop: 0, paddingRight: 0, paddingBottom: 0, paddingLeft: 0, itemSpacing: 0, counterAxisSpacing: 0,
      primaryAxisAlignItems: "MIN", counterAxisAlignItems: "MIN", primaryAxisSizingMode: "AUTO", counterAxisSizingMode: "AUTO", layoutWrap: "NO_WRAP",
      layoutSizingHorizontal: "FIXED", layoutSizingVertical: "FIXED", fills: [{ type: "SOLID", color: { r: 1, g: 1, b: 1 } }] }),
    createText: () => {
      const t = node("TEXT", { characters: "", fontName: { family: "Inter", style: "Regular" }, fontSize: 12, lineHeight: { unit: "AUTO" }, letterSpacing: { unit: "PERCENT", value: 0 },
        textAlignHorizontal: "LEFT", textAlignVertical: "TOP", textAutoResize: "WIDTH_AND_HEIGHT", textTruncation: "DISABLED", textStyleId: "",
        fills: [{ type: "SOLID", color: { r: 0, g: 0, b: 0 } }] });
      // as Figma does: maxLines takes only while the box grows with its text (seen live: null under NONE)
      let lines = null;
      Object.defineProperty(t, "maxLines", { get: () => lines, set: (v) => { if (/HEIGHT/.test(t.textAutoResize)) lines = v; }, enumerable: true });
      return t;
    },
  };
  return figma;
}
const run = async (body) => { const figma = standIn(); const out = await new Async("figma", body)(figma); return { out, figma }; };

let n = 0;
const ok = async (name, fn) => { await fn(); n++; console.log(`ok   ${name}`); };

await ok("the body is serialise.js's serialiser up to its walk, then the test: nothing pasted, nothing to keep in sync", async () => {
  const body = coverageBody();
  assert.ok(body.includes(SERIALISE.slice(SERIALISE.indexOf("function h("), SERIALISE.indexOf("\nfunction walk("))), "the serialiser verbatim");
  assert.ok(!body.includes("function walk(") && body.endsWith(TEST), "no walk, the test whole at the end");
  assert.ok(/^\/\/ Generated by scripts\/coverage-body\.mjs/.test(body), "says it is generated");
  assert.ok(!/paste/i.test(TEST.replace(/never paste them in/, "")), "coverage-test.js asks no one to paste");
});

await ok("coverage-test.js alone has no serialiser: run alone, it fails at once rather than certify nothing", async () => {
  await assert.rejects(() => new Async("figma", TEST)(standIn()), /h is not defined|ser is not defined/);
});

await ok("today's serialiser has no blind spot on the stand-in, and the scratch nodes are removed", async () => {
  const { out, figma } = await run(coverageBody());
  assert.deepEqual(out.errored, []);
  // every check() the test makes, and the child-order one
  assert.equal(out.checked, TEST.match(/^check\(/gm).length + 1);
  assert.deepEqual(out.blindSpots, [], `blind: ${out.blindSpots.join(", ")}`);
  assert.equal(out.pass, true);
  const kept = figma.made.filter((x) => !x.removed && !x.parent);
  assert.equal(kept.length, 0, "every top-level scratch node removed");
});

await ok("a check whose mutation changes nothing reads as a blind spot: FIXED set again, maxLines set while the box is fixed", async () => {
  const noop = TEST.replace("n.layoutSizingHorizontal = 'HUG'", "n.layoutSizingHorizontal = 'FIXED'").replace("t.textAutoResize = 'HEIGHT';\n", "");
  assert.notEqual(noop, TEST, "the mutations to undo are in coverage-test.js");
  const { out } = await run(coverageBody(SERIALISE, noop));
  assert.deepEqual(out.blindSpots, ["layoutSizingHorizontal", "maxLines"]);
});

await ok("a serialiser that stops reading the width shows it as a blind spot", async () => {
  const blind = SERIALISE.replace(" if(n.layoutSizingHorizontal==='FIXED') p.push('W'+Math.round(n.width));", "");
  assert.notEqual(blind, SERIALISE, "the width read is in serialise.js");
  const { out } = await run(coverageBody(blind));
  assert.deepEqual(out.blindSpots, ["width (FIXED)"]);
});

await ok("a serialiser that stops reading a property shows it as a blind spot, never a pass", async () => {
  const blind = SERIALISE.replace("  if (n.maxWidth!==undefined) p.push('maxW'+n.maxWidth);\n", "");
  assert.notEqual(blind, SERIALISE, "the line to drop is in serialise.js");
  const { out } = await run(coverageBody(blind));
  assert.deepEqual(out.blindSpots, ["maxWidth"]);
  assert.equal(out.pass, false);
});

await ok("a serialise.js with no walk is refused by name", async () => {
  assert.throws(() => coverageBody("function h(){}", TEST), /serialise\.js has no `function walk\(`/);
});

console.log(`${n} passed`);
