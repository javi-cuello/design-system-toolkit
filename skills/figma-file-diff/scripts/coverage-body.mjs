#!/usr/bin/env node
/*
 * The coverage test's runnable body: serialise.js's serialiser (h, ser and
 * everything they read, up to its walk), then coverage-test.js. The test must
 * hash with the serialiser it certifies, so the two are joined here rather
 * than pasted and kept in sync by hand (toolkit-standard §D 23).
 *
 *   node scripts/coverage-body.mjs              print the body: pass it to figma_execute in a scratch file
 *   node scripts/coverage-body.mjs --out <file> write it there instead
 */
import fs from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const read = (f) => fs.readFileSync(fileURLToPath(new URL(f, import.meta.url)), 'utf8');

export function coverageBody(serialise = read('./serialise.js'), test = read('./coverage-test.js')) {
  const end = serialise.indexOf('\nfunction walk(');
  if (end < 0) throw new Error('serialise.js has no `function walk(`, where its serialiser ends: the coverage body cannot be cut from it');
  return `// Generated by scripts/coverage-body.mjs from serialise.js and coverage-test.js. Never edit: run it again.\n\n${serialise.slice(0, end).trimEnd()}\n\n// ---- coverage-test.js ----\n${test}`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(fs.realpathSync(process.argv[1])).href) {
  const i = process.argv.indexOf('--out');
  const body = coverageBody();
  if (i > 0) {
    if (!process.argv[i + 1]) { console.error('usage: node scripts/coverage-body.mjs [--out <file>]'); process.exit(2); }
    fs.writeFileSync(process.argv[i + 1], body);
    console.log(`coverage body written to ${process.argv[i + 1]}`);
  } else process.stdout.write(body);
}
